# نشانگر «در حال تایپ است...» قبل از پردازش‌های کند (AI/OCR/STT/jozve) —
# ارزون‌ترین و استانداردترین راه ممکن برای این‌که بات زنده و پاسخگو به‌نظر
# برسه، مستقل از پیام‌های متنیِ «⏳ در حال پردازش» که جداگانه هم وجود دارن.
#
# عمداً فقط یه بار فرستاده می‌شه، نه با یه حلقه‌ی پس‌زمینه برای تمدید
# دوره‌ای هر ۴-۵ ثانیه (که تلگرام برای عملیات طولانی لازم داره تا نشانگر
# قطع نشه): این یه نشانگر سریعِ «دیدمت، دارم کار می‌کنم» برای چند ثانیه‌ی
# اول است، نه جایگزین پیام متنیِ «در حال پردازش» که برای عملیات واقعاً
# طولانی (OCR/STT/jozve) از قبل وجود داره و ناپدید نمی‌شه. پیچیده‌کردنش با
# یه تایمر پس‌زمینه، هزینه‌ی نگه‌داری‌اش رو برای یه بهبود صرفاً تزئینی
# توجیه نمی‌کنه.

import logging

from telegram.constants import ChatAction

logger = logging.getLogger(__name__)


async def send_typing(bot, chat_id: int) -> None:
    """صرفاً یه نشانگر UI است — شکستش (هر دلیلی، شبکه یا هرچی) نباید جلوی
    فیچر اصلی رو بگیره، پس بی‌سروصدا قورت داده می‌شه، نه raise."""
    try:
        await bot.send_chat_action(chat_id=chat_id, action=ChatAction.TYPING)
    except Exception as e:
        logger.debug("send_chat_action skipped: %s", e)
